from hangul import *
from 니은첨가 import 니은첨가대상

def 연음(음절들):
    for i in range(len(음절들) - 1):
        앞=음절들[i]
        뒤=음절들[i + 1]

        if 앞['한글아님'] is not None:
            continue
        if 앞['종']=='' or 앞['종']=='ㅇ' or 뒤['초']!= 'ㅇ':
            continue

        #15항
        if 앞['형태소끝'] and not 앞['다음형식']:
            if 뒤['중'] in ['ㅏ', 'ㅓ', 'ㅗ', 'ㅜ', 'ㅟ']:
                #겹받침도 대표음 하나만 옮겨감 (넋 없다[너겁따], 닭 앞에[다가페])
                원래받침 = 앞['종']
                뒤['초'] = 대표음[원래받침]
                앞['종'] = ''
                continue   # 이미 처리했으니 아래 기본 연음으로 덮어쓰지 않음

            if 니은첨가대상(앞, 뒤):
                continue   # 솜이불 같은 경우는 연음이 아니라 ㄴ첨가(니은첨가.py)가 처리

        #13,14항
        if 앞['어절끝']:
            continue
        
        #기본
        if 앞['종'] == 'ㅎ':
            앞['종'] = ''
            뒤['초'] = 'ㅇ'
        elif 앞['종'] in ('ㄶ', 'ㅀ'):
            뒤['초'] = 겹받침[앞['종']][0]
            앞['종'] = ''
        elif 앞['종'] in 겹받침:
            뒤['초'] = 겹받침[앞['종']][1]
            앞['종'] = 겹받침[앞['종']][0]
        else:
            뒤['초'] = 앞['종'] #위아래 줄 바꾸면 큰일난디...
            앞['종'] = ''


    return 음절들