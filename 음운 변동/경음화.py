from hangul import *

된소리 = {'ㄱ': 'ㄲ', 'ㄷ': 'ㄸ', 'ㅂ': 'ㅃ', 'ㅅ': 'ㅆ', 'ㅈ': 'ㅉ'}

#끝소리규칙보다 먼저 실행해야 함 (ㄺ,ㄼ,ㄾ 같은 겹받침 정보가 필요하기 때문)
def 경음화(음절들):
    for i in range(len(음절들) - 1):
        앞 = 음절들[i]
        뒤 = 음절들[i + 1]

        if 앞['한글아님'] is not None or 뒤['한글아님'] is not None:
            continue

        종 = 앞['종']
        초 = 뒤['초']
        if 종 == '' or 초 not in 된소리:
            continue

        #제27항: 관형사형 어미 -(으)ㄹ 뒤 (어절 사이에도 적용: 할 것을[할껏을], 갈 데[갈떼])
        if 종 == 'ㄹ' and 앞['현재품사'].startswith('ETM'):
            뒤['초'] = 된소리[초]
            continue

        if 앞['어절끝']:
            continue

        #어간 + 어미의 경계에서만 쓰는 조건 (한다·먹는다처럼 받침이 어미 쪽에 있으면 제외)
        어간 = 앞['경계'] and 앞['다음품사'].startswith('E')

        #제11항 다만: 용언 어간 ㄺ + ㄱ -> [ㄹ] + 된소리 (읽게[일께], 맑게[말께])
        if 어간 and 종 == 'ㄺ' and 초 == 'ㄱ':
            앞['종'] = 'ㄹ'
            뒤['초'] = 'ㄲ'
            continue

        #제23항: 받침 ㄱ,ㄷ,ㅂ(으로 발음되는 받침) 뒤 ㄱ,ㄷ,ㅂ,ㅅ,ㅈ (국밥[국빱], 먹고[먹꼬], 옷도[옫또])
        if 대표음[종] in ('ㄱ', 'ㄷ', 'ㅂ'):
            뒤['초'] = 된소리[초]

        #제24항: 어간 받침 ㄴ(ㄵ),ㅁ(ㄻ) 뒤 어미 ㄱ,ㄷ,ㅅ,ㅈ (신고[신꼬], 앉고[안꼬], 삼고[삼꼬])
        #제25항: 어간 받침 ㄼ,ㄾ 뒤 어미 ㄱ,ㄷ,ㅅ,ㅈ (넓게[널께], 핥다[할따])
        elif 어간 and 종 in ('ㄴ', 'ㄵ', 'ㅁ', 'ㄻ', 'ㄼ', 'ㄾ') and 초 in ('ㄱ', 'ㄷ', 'ㅅ', 'ㅈ'):
            뒤['초'] = 된소리[초]

    #한자어(ㄹ 뒤 ㄷ,ㅅ,ㅈ: 발달·일시), 사이시옷 경음화는 형태소 정보만으로 구분이 안 되어 미구현
    return 음절들
