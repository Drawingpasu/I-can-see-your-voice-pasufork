from hangul import *

#제12항: ㅎ이 관여하는 규칙 (격음화·ㅎ+ㅅ)
#(파일 이름에 'ㅎ' 자모를 쓰면 import가 안 되어서 '히읗규칙'으로 지음)

거센소리 = {'ㄱ': 'ㅋ', 'ㄷ': 'ㅌ', 'ㅈ': 'ㅊ'}

#ㅎ(ㄶ,ㅀ) 받침을 가진 앞 음절에 남는 받침
ㅎ뒤남는받침 = {'ㅎ': '', 'ㄶ': 'ㄴ', 'ㅀ': 'ㄹ'}

#뒤 첫소리가 ㅎ일 때: 앞 받침 -> (앞에 남는 받침, 뒤에 오는 거센소리)
ㅎ앞받침 = {
    'ㄱ': ('', 'ㅋ'), 'ㄲ': ('', 'ㅋ'), 'ㅋ': ('', 'ㅋ'), 'ㄳ': ('', 'ㅋ'), 'ㄺ': ('ㄹ', 'ㅋ'),   # 각하[가카], 읽히다[일키다]
    'ㅂ': ('', 'ㅍ'), 'ㅍ': ('', 'ㅍ'), 'ㅄ': ('', 'ㅍ'), 'ㄼ': ('ㄹ', 'ㅍ'), 'ㄿ': ('ㄹ', 'ㅍ'), # 입학[이팍], 넓히다[널피다]
    'ㄷ': ('', 'ㅌ'), 'ㅅ': ('', 'ㅌ'), 'ㅆ': ('', 'ㅌ'), 'ㅌ': ('', 'ㅌ'), 'ㅊ': ('', 'ㅌ'), 'ㄾ': ('ㄹ', 'ㅌ'),  # 맏형[마텽], 옷하고[오타고]
    'ㅈ': ('', 'ㅊ'), 'ㄵ': ('ㄴ', 'ㅊ'),                                                          # 앉히다[안치다], 꽂히다[꼬치다]
}

def 히읗규칙(음절들):
    for i in range(len(음절들) - 1):
        앞 = 음절들[i]
        뒤 = 음절들[i + 1]

        if 앞['한글아님'] is not None or 뒤['한글아님'] is not None:
            continue
        if 앞['어절끝']:
            continue

        종 = 앞['종']
        초 = 뒤['초']

        #ㅎ(ㄶ,ㅀ) + ㄱ,ㄷ,ㅈ -> ㅋ,ㅌ,ㅊ (좋고[조코], 않다[안타], 싫지[실치])
        #ㅎ(ㄶ,ㅀ) + ㅅ -> ㅆ (닿소[다쏘])
        if 종 in ㅎ뒤남는받침:
            if 초 in 거센소리:
                앞['종'] = ㅎ뒤남는받침[종]
                뒤['초'] = 거센소리[초]
            elif 초 == 'ㅅ':
                앞['종'] = ㅎ뒤남는받침[종]
                뒤['초'] = 'ㅆ'

        #제17항 붙임: ㄷ + 히 -> 치 (닫히다[다치다], 굳히다[구치다], 묻히다[무치다])
        elif 종 == 'ㄷ' and 초 == 'ㅎ' and 뒤['중'] == 'ㅣ':
            앞['종'] = ''
            뒤['초'] = 'ㅊ'

        #받침 + ㅎ -> 거센소리 (각하[가카], 입학[이팍], 맏형[마텽])
        elif 초 == 'ㅎ' and 종 in ㅎ앞받침:
            남는, 변환 = ㅎ앞받침[종]
            앞['종'] = 남는
            뒤['초'] = 변환

    return 음절들
