#제8항~제11항: 음절 끝에서는 ㄱ,ㄴ,ㄷ,ㄹ,ㅁ,ㅂ,ㅇ 일곱 소리만 난다.
#연음·격음화 등으로 옮겨지지 않고 남은 받침을 대표음으로 바꾼다.
def 끝소리규칙(음절들):
    for 음절 in 음절들:
        if 음절['한글아님'] is not None or 음절['종'] == '':
            continue

        if 음절['종'] == 'ㅎ':      # 남은 ㅎ은 ㄷ으로 (놓는 -> 녿는 -> 논는: 이후 비음화)
            음절['종'] = 'ㄷ'
        else:
            음절['종'] = 대표음[음절['종']]

    return 음절들


#제10항 [다만]: 밟-은 자음 앞에서 [밥], 넓-은 넓죽하다·넓둥글다에서만 [넙]
#(초ㅂ+중ㅏ+종ㄼ은 '밟'뿐이라 자모로 식별 가능)
#히읗규칙·경음화 앞에서 실행 (밟히다[발피다]처럼 뒤가 ㅎ이면 건드리지 않고 히읗규칙에 맡김)
넓_뒤음절 = [('ㅈ', 'ㅜ', 'ㄱ'), ('ㄷ', 'ㅜ', 'ㅇ')]   # 죽, 둥

def 밟다예외(음절들):
    for i in range(len(음절들) - 1):
        앞 = 음절들[i]
        뒤 = 음절들[i + 1]

        if 앞['한글아님'] is not None or 뒤['한글아님'] is not None:
            continue
        if 앞['어절끝'] or 앞['종'] != 'ㄼ' or 뒤['초'] in ('', 'ㅇ', 'ㅎ'):
            continue

        if 앞['초'] == 'ㅂ' and 앞['중'] == 'ㅏ':                          # 밟
            앞['종'] = 'ㅂ'
        elif 앞['초'] == 'ㄴ' and 앞['중'] == 'ㅓ' and (뒤['초'], 뒤['중'], 뒤['종']) in 넓_뒤음절:  # 넓죽-, 넓둥글-
            앞['종'] = 'ㅂ'

    return 음절들
