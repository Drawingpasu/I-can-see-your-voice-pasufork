from hangul import *


def 비음화(음절들):
    for i in range(len(음절들)-1):
        앞=음절들[i]
        뒤=음절들[i+1]

        if 앞['어절끝']:
            continue

        if 앞['한글아님'] is not None or 뒤['한글아님'] is not None:
            continue

        if 앞['종'] == '':
            continue

        대표 = 대표음[앞['종']]   # 끝소리 규칙: 겹받침·ㄲ·ㅅ 등을 대표음으로

        #ㄹ의 비음화,제19항 (붙임: ㄱ,ㅂ 뒤의 ㄹ도 ㄴ으로)
        if 뒤['초']=='ㄹ' and 대표 in ['ㅁ','ㅇ','ㄱ','ㅂ']:
            뒤['초']='ㄴ'

        #파열음의 비음화,제18항
        if 뒤['초'] in ['ㄴ','ㅁ']:

            if 대표=='ㄱ':
                앞['종']='ㅇ'
            elif 대표=='ㄷ' or 앞['종']=='ㅎ':
                앞['종']='ㄴ'
            elif 대표=='ㅂ':
                앞['종']='ㅁ'
            else:
                앞['종']=대표    # ㄵ,ㄻ,ㄼ 등 겹받침이 ㄴ/ㅁ/ㄹ로 단순화 (앉는[안는], 닮네[담네])

    return 음절들
