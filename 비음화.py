from hangul import *


def 비음화(음절들):
    for i in range(len(음절들)-1):
        앞=음절들[i]
        뒤=음절들[i+1]

        if 앞['어절끝']:
            continue

        if 앞['한글아님'] is not None:
            continue
        
        #ㄹ의 비음화,제19항
        if 앞['종'] in ['ㅁ','ㅇ'] and 뒤['초']==ㄹ:
            뒤['초']=ㄴ
            
        #파열음의 비음화,제18항
        if 뒤['초']in ['ㄴ','ㅁ']:
            
            if 앞['종']in['ㄱ','ㄲ','ㅋ','ㄳ','ㄺ']:
                앞['종']=ㅇ

            if 앞['종']in['ㄷ','ㅅ','ㅆ','ㅈ','ㅊ','ㅌ','ㅎ']:
                앞['종']=ㄴ
                
            if 앞['종']in['ㅂ','ㅍ','ㄼ','ㄿ','ㅄ']:
                앞['종']=ㅁ



            

        

                
