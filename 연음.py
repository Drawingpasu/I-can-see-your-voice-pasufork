from hangul import *

def 연음(음절들):
    for i in range(len(음절들) - 1):
        앞=음절들[i]
        뒤=음절들[i + 1]

        if 앞['한글아님'] is not None:
            continue
        if 앞['종']=='' or 앞['종']=='ㅇ' or 뒤['초']!= 'ㅇ':
            continue

        #15항
        if 앞['형태소끝'] and not 앞['다음형식']:
            if 뒤['중'] in ['ㅏ', 'ㅓ', 'ㅗ', 'ㅜ', 'ㅟ']:
                원래받침 = 앞['종']
                뒤['초'] = 대표음[원래받침]
                앞['종'] = ''

        #13,14항
        if 앞['어절끝']:
            continue
        
        #기본
        if 앞['종'] == 'ㅎ':
            앞['종'] = ''
            뒤['초'] = 'ㅇ'
        elif 앞['종'] in ('ㄶ', 'ㅀ'):
            뒤['초'] = 겹받침[앞['종']][0]
            앞['종'] = ''
        elif 앞['종'] in 겹받침:
            뒤['초'] = 겹받침[앞['종']][1]
            앞['종'] = 겹받침[앞['종']][0]
        else:
            뒤['초'] = 앞['종'] #위아래 줄 바꾸면 큰일난디...
            앞['종'] = ''


    return 음절들